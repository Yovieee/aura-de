#!/usr/bin/env python3
"""Exercise real portal consent, compositor readback, PipeWire frames and revocation."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

from integration_desktop import command, require
from session_smoke import Input
from smoke_nested import ROOT, start_xvfb, stop, tail

BUS = 'org.freedesktop.impl.portal.desktop.aura'
PATH = '/org/freedesktop/portal/desktop'
INTERFACE = 'org.freedesktop.impl.portal.ScreenCast'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--no-build', action='store_true')
    parser.add_argument('--inside-bus', action='store_true', help=argparse.SUPPRESS)
    parser.add_argument('--log-dir', type=Path, default=ROOT / 'target' / 'screencast-smoke-logs')
    args = parser.parse_args()
    if not args.inside_bus:
        return subprocess.run(['dbus-run-session', '--', sys.executable, str(Path(__file__).resolve()),
                               *sys.argv[1:], '--inside-bus'], cwd=ROOT, check=False).returncode
    if not args.no_build:
        subprocess.run(['cargo', 'build', '--workspace', '--bins', '--locked'], cwd=ROOT, check=True)
        subprocess.run(['cargo', 'build', '-p', 'aura-session', '--examples', '--locked'], cwd=ROOT, check=True)
        subprocess.run(['cargo', 'build', '-p', 'aura-compositor', '--example', 'smoke_client', '--locked'], cwd=ROOT, check=True)
    target = Path(json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--locked', '--no-deps', '--format-version', '1'], cwd=ROOT))['target_directory']) / 'debug'
    env = os.environ.copy()
    env.update(LIBGL_ALWAYS_SOFTWARE='1', RUST_LOG='info', AURA_COMPOSITOR_GLASS='1')
    # The capability must be generated by the real supervisor and never reach test apps.
    env.pop('AURA_CAPTURE_TOKEN', None)
    env.pop('AURA_CAPTURE_SOCKET', None)
    env.pop('AURA_CAPTURE_OWNER_PID', None)
    args.log_dir.mkdir(parents=True, exist_ok=True)
    processes, outputs, logs = [], [], {}
    daemon = session = xvfb = input_ = None
    evidence = {}

    def launch(name, argv):
        log = args.log_dir / f'{name}.log'
        output = log.open('w')
        outputs.append(output)
        logs[name] = log
        process = subprocess.Popen(argv, cwd=ROOT, env=env, stdout=output, stderr=subprocess.STDOUT)
        processes.append(process)
        return process

    def wait_for(predicate, description, timeout=15):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if daemon is not None:
                require(daemon.poll() is None, 'Private PipeWire daemon exited')
            if session is not None:
                require(session.poll() is None, 'Aura supervisor exited')
            result = predicate()
            if result:
                return result
            time.sleep(0.025)
        raise RuntimeError(f'Timed out waiting for {description}')

    def node_exists(node):
        result = subprocess.run([str(target / 'examples' / 'capture_frames'), '--node-exists', str(node)],
                                env=env, capture_output=True, text=True, timeout=4, check=True)
        require(result.stdout.strip() in ('node_exists=true', 'node_exists=false'),
                'Registry check returned no definitive result')
        return result.stdout.strip() == 'node_exists=true'

    try:
        xvfb = start_xvfb(env)
        with tempfile.TemporaryDirectory(prefix='aura-capture-smoke-') as directory:
            runtime = Path(directory)
            os.chmod(runtime, 0o700)
            env.update(XDG_RUNTIME_DIR=directory, AURA_CONTROL_SOCKET=str(runtime / 'aura-control.sock'),
                       AURA_WINIT_RESOLUTION='1024x640', AURA_OUTPUT_SCALE='1', PIPEWIRE_REMOTE='pipewire-0')
            daemon = launch('pipewire', ['pipewire'])
            wait_for(lambda: (runtime / 'pipewire-0').is_socket(), 'private PipeWire socket')
            session = launch('session', [str(target / 'aura-session'), '--socket', 'wayland-capture-smoke'])
            control = runtime / 'aura-control.sock'

            def status():
                return json.loads(command(control, 'status')) if control.exists() else {}

            wait_for(lambda: status().get('capture_available') and status().get('mapped_layers') == 2,
                     'real compositor capture source and shell buffers')

            def portal_ready():
                result = subprocess.run(['gdbus', 'call', '--session', '--dest', BUS, '--object-path', PATH,
                    '--method', 'org.freedesktop.DBus.Properties.Get', INTERFACE, 'AvailableSourceTypes'],
                    capture_output=True, text=True, timeout=2, check=False)
                return result.returncode == 0 and 'uint32 1' in result.stdout

            wait_for(portal_ready, 'ready monitor capability from actual source/daemon probe')
            input_ = Input(env['DISPLAY'])

            def request(name, arguments):
                process = launch(name, [str(target / 'examples' / 'portal_request'), *arguments])
                wait_for(lambda: 'PORTAL_PENDING' in logs[name].read_text(), f'{name} frontend Start')
                return process

            def consent_ready():
                wait_for(lambda: status().get('mapped_layers') == 3, 'real consent overlay buffer')
                time.sleep(0.15)  # Client seat/keyboard binding follows its first configured buffer.

            denied = request('denied', ['--expect-denied'])
            consent_ready()
            input_.key(0xff0d)  # Default selection must deny.
            require(denied.wait(timeout=10) == 0, 'Default consent denial failed')
            require('PORTAL_DENIED' in logs['denied'].read_text(), 'Denial did not return cancellation response')
            wait_for(lambda: status().get('mapped_layers') == 2 and status().get('capture_subscribers') == 0,
                     'denied request has no capture subscription')
            evidence['default_denial'] = 'no stream or subscription'

            cancelled = request('cancelled', ['--cancel'])
            require(cancelled.wait(timeout=10) == 0, 'Request.Close failed')
            require('PORTAL_CANCELLED' in logs['cancelled'].read_text(), 'Missing cancellation response')
            wait_for(lambda: status().get('mapped_layers') == 2 and status().get('capture_subscribers') == 0,
                     'cancelled consent UI and subscription cleanup')
            evidence['request_cancellation'] = 'overlay removed, no stream'

            def approve(name):
                frontend = request(name, ['--hold-seconds', '60'])
                consent_ready()
                input_.key(0xff53)  # Explicitly select Allow.
                input_.key(0xff0d)
                def stream_ready():
                    require(frontend.poll() is None, f'{name} frontend exited before returning a real stream')
                    return re.search(r'PORTAL_STREAM node_id=(\d+) width=(\d+) height=(\d+)', logs[name].read_text())
                stream = wait_for(stream_ready, f'{name} actual PipeWire node', 15)
                node, width, height = map(int, stream.groups())
                require((width, height) == (1024, 640), 'Portal size does not match real output')
                require(node_exists(node), 'Portal returned a nonexistent PipeWire node')
                return frontend, node, width, height

            def receive(name, node, width, height):
                consumer = launch(name, [str(target / 'examples' / 'capture_frames'), '--node', str(node), str(width), str(height)])
                require(consumer.wait(timeout=15) == 0, 'Real PipeWire consumer did not receive valid RGBA frames')
                match = re.search(r'received=(\d+).*checksum=([a-f0-9]+)', logs[name].read_text())
                require(match is not None and int(match[1]) >= 10, 'Consumer did not verify ten actual frames')
                return match[2]

            frontend, node, width, height = approve('approved')
            first_checksum = receive('consumer-before', node, width, height)
            # Change actual desktop pixels, then check the existing stream follows the scene.
            app_env = env | {'WAYLAND_DISPLAY': 'wayland-capture-smoke'}
            app_log = args.log_dir / 'scene-client.log'
            logs['scene-client'] = app_log
            app_output = app_log.open('w'); outputs.append(app_output)
            app = subprocess.Popen([str(target / 'examples' / 'smoke_client'), '--frames', '2', '--stay', '--idle-on-ready',
                                    '--start-fullscreen', '--title', 'ScreenCast pixel probe'], cwd=ROOT, env=app_env, stdout=app_output, stderr=subprocess.STDOUT)
            processes.append(app)
            wait_for(lambda: 'SMOKE_CLIENT_OK' in app_log.read_text(), 'real fullscreen scene client buffers')
            require('fullscreen=active' in app_log.read_text(), 'Client did not enter fullscreen')
            time.sleep(0.15)
            second_checksum = receive('consumer-after', node, width, height)
            require(first_checksum != second_checksum, 'Capture did not reflect actual changed desktop pixels')
            evidence['real_composed_frames'] = {'node_id': node, 'size': [width, height],
                'before_checksum': first_checksum, 'after_checksum': second_checksum, 'frames_per_consumer': 10}
            wait_for(lambda: status().get('capture_subscribers') == 1, 'one active capture subscription')
            time.sleep(0.65)  # Shell worker must display its asynchronous sharing indicator.
            input_.click(924, 16)
            wait_for(lambda: status().get('capture_subscribers') == 0, 'shell Stop revoking capture')
            wait_for(lambda: not node_exists(node), 'revocation removing the real PipeWire node', 6)
            frontend.terminate()
            require(frontend.wait(timeout=5) == 0, 'Frontend did not handle already-closed portal session')
            evidence['shell_stop'] = 'Stop above fullscreen revoked subscription and removed node'

            reopened, node2, width, height = approve('reapproved')
            receive('consumer-reapproved', node2, width, height)
            reopened.terminate()
            require(reopened.wait(timeout=5) == 0, 'Session.Close did not complete')
            wait_for(lambda: not node_exists(node2) and status().get('capture_subscribers') == 0,
                     'explicit session close cleaning source and PipeWire node', 6)
            evidence['fresh_consent_after_revoke'] = 'new real stream delivered frames, close cleaned resources'

            disconnected, node3, _, _ = approve('disconnect')
            disconnected.kill(); disconnected.wait(timeout=5)
            wait_for(lambda: not node_exists(node3) and status().get('capture_subscribers') == 0,
                     'frontend disconnect cleanup', 6)
            evidence['frontend_disconnect'] = 'stream/node removed'
            stop(app)
            session.terminate()
            require(session.wait(timeout=10) == 0, 'Supervisor shutdown failed')
            require(not (runtime / 'aura-capture.sock').exists(), 'Capture socket leaked')
            require(not control.exists() and not (runtime / 'wayland-capture-smoke').exists(), 'Desktop socket leaked')
        (args.log_dir / 'results.json').write_text(json.dumps(evidence, indent=2) + '\n')
        print('PASS: actual consent, changed compositor pixels over PipeWire, user Stop, fresh consent, cancellation and disconnect cleanup.')
        print(f'Logs and frame evidence: {args.log_dir}')
        return 0
    except Exception as error:
        print(f'FAIL: {error}', file=sys.stderr)
        for name, log in logs.items():
            print(f'{name}:\n{tail(log)}', file=sys.stderr)
        return 1
    finally:
        if input_:
            input_.close()
        for process in reversed(processes):
            stop(process)
        stop(xvfb)
        for output in outputs:
            output.close()


if __name__ == '__main__':
    sys.exit(main())
